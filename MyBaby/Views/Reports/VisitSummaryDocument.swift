import SwiftUI

/// The visit summary as a printable page, shared as a PDF (see `Exporter.pdf`). Laid out like
/// `ReportDocument`, so the two read as a set.
struct VisitSummaryDocument: View {
    let summary: VisitSummary
    let unit: VolumeUnit
    let growthUnits: GrowthUnits

    var body: some View {
        VStack(alignment: .leading, spacing: 18) {
            header
            questionsSection
            if !summary.lastVisitNotes.isEmpty {
                linesSection(String(localized: "From the last visit"), [summary.lastVisitNotes])
            }
            HStack(alignment: .top, spacing: 24) {
                rowsSection(String(localized: "Feeding"), summary.feedingRows(unit: unit))
                rowsSection(String(localized: "Diapers"), summary.diaperRows)
                rowsSection(String(localized: "Sleep"), summary.sleepRows)
            }
            if !summary.flaggedDiapers.isEmpty {
                linesSection(String(localized: "Poop colors to mention"), summary.flaggedDiapers.map(summary.flaggedLine))
            }
            growthSection
            if !summary.temperatures.isEmpty {
                linesSection(String(localized: "Temperatures"), summary.temperatures.map { summary.temperatureLine($0, unit: unit) })
            }
            linesSection(String(localized: "Medicine given"), summary.medicines.map(summary.medicineLine), empty: String(localized: "None logged."))
            if !summary.allergies.isEmpty {
                linesSection(String(localized: "Allergies"), summary.allergies.map(\.reportLine))
            }
            if !summary.reactions.isEmpty {
                linesSection(String(localized: "Allergic reactions in this period"), summary.reactions.map(\.reportLine))
            }
            vaccineSection
            Text("Generated by MyBaby on \(Date.now.formatted(date: .long, time: .shortened)). Logged by parents; not a medical record.")
                .font(.system(size: 9))
                .foregroundStyle(.gray)
        }
        .padding(40)
        .frame(width: 612, alignment: .leading)
        .background(Color.white)
        .foregroundStyle(.black)
    }

    private var header: some View {
        VStack(alignment: .leading, spacing: 4) {
            Text("\(summary.babyName) — Visit summary")
                .font(.system(size: 24, weight: .bold))
            Text(appointmentLine)
                .font(.system(size: 12, weight: .medium))
            if !summary.place.isEmpty {
                Text(summary.place)
                    .font(.system(size: 11))
            }
            HStack(spacing: 6) {
                if let birthDate = summary.birthDate {
                    Text("Born \(birthDate.formatted(date: .abbreviated, time: summary.hasBirthTime ? .shortened : .omitted)) · \(Format.age(birthDate: birthDate, now: summary.appointmentDate))")
                    Text("·")
                }
                Text("\(summary.periodTitle) (\(summary.start.formatted(date: .abbreviated, time: .omitted)) – \(summary.end.formatted(date: .abbreviated, time: .omitted)))")
            }
            .font(.system(size: 11))
            .foregroundStyle(.gray)
            Text(summary.averagesNote)
                .font(.system(size: 9))
                .foregroundStyle(.gray)
        }
    }

    private var appointmentLine: String {
        var line = "\(summary.appointmentTitle), \(summary.appointmentDate.formatted(date: .long, time: .shortened))"
        if !summary.provider.isEmpty { line += " · \(summary.provider)" }
        return line
    }

    private var questionsSection: some View {
        VStack(alignment: .leading, spacing: 5) {
            sectionTitle(String(localized: "Questions to ask"))
            if summary.questions.isEmpty {
                Text("None written down.").font(.system(size: 10)).foregroundStyle(.gray)
            }
            ForEach(summary.questions) { question in
                HStack(alignment: .firstTextBaseline, spacing: 6) {
                    Text(question.isAsked ? "☑" : "☐")
                    Text(question.text)
                }
                .font(.system(size: 11))
            }
        }
    }

    private func rowsSection(_ title: String, _ rows: [SummaryRow]) -> some View {
        VStack(alignment: .leading, spacing: 5) {
            sectionTitle(title)
            ForEach(rows) { row in
                VStack(alignment: .leading, spacing: 1) {
                    Text(row.label).font(.system(size: 9)).foregroundStyle(.gray)
                    Text(row.value).font(.system(size: 13, weight: .semibold))
                    if let detail = row.detail {
                        Text(detail).font(.system(size: 9)).foregroundStyle(.gray)
                    }
                }
            }
        }
        .frame(maxWidth: .infinity, alignment: .leading)
    }

    /// Left out when nothing has been measured.
    @ViewBuilder
    private var growthSection: some View {
        let rows = summary.growthRows(growthUnits)
        if !rows.isEmpty {
            VStack(alignment: .leading, spacing: 5) {
                rowsSection(String(localized: "Growth"), rows)
                if summary.weight?.percentile != nil || summary.length?.percentile != nil
                    || summary.headCircumference?.percentile != nil {
                    Text("Percentiles from the WHO Child Growth Standards, by age from the birthday.")
                        .font(.system(size: 9))
                        .foregroundStyle(.gray)
                }
            }
        }
    }

    private var vaccineSection: some View {
        VStack(alignment: .leading, spacing: 5) {
            sectionTitle(String(localized: "Vaccines given in this period"))
            if summary.vaccinesGiven.isEmpty {
                Text("None logged.").font(.system(size: 10)).foregroundStyle(.gray)
            }
            ForEach(summary.vaccinesGiven) { vaccine in
                Text(summary.vaccineLine(vaccine)).font(.system(size: 10))
            }
            if !summary.vaccinesDue.isEmpty {
                Text("Upcoming").font(.system(size: 10, weight: .semibold)).padding(.top, 4)
                ForEach(summary.vaccinesDue) { vaccine in
                    Text(summary.vaccineLine(vaccine)).font(.system(size: 10))
                }
            }
        }
    }

    private func linesSection(_ title: String, _ lines: [String], empty: String? = nil) -> some View {
        VStack(alignment: .leading, spacing: 5) {
            sectionTitle(title)
            if lines.isEmpty, let empty {
                Text(empty).font(.system(size: 10)).foregroundStyle(.gray)
            }
            ForEach(Array(lines.enumerated()), id: \.offset) { item in
                Text(item.element).font(.system(size: 10))
            }
        }
    }

    private func sectionTitle(_ title: String) -> some View {
        Text(title.uppercased())
            .font(.system(size: 10, weight: .bold))
            .foregroundStyle(Color(red: 0.75, green: 0.3, blue: 0.45))
    }
}
